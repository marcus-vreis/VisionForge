"""Build the paper's numbers, table and figures from ``results/summary.json``.

Nothing in ``paper/main.tex`` is typed by hand: every number in the text is a
macro written here to ``paper/numbers.tex``, the per-cell table goes to
``paper/table_cells.tex`` and the two figures to ``paper/fig_*.pdf``.

    .venv\\Scripts\\python.exe research\\seed_variance\\make_paper_assets.py
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
SUMMARY = RESULTS / "summary.json"
PAPER = HERE / "paper"

DATASET_LABELS = {
    "usk_full": "USK-Coffee",
    "usk_10pct": "USK-Coffee 10\\%",
    "beans": "Beans",
}
PLOT_DATASET_LABELS = {
    "usk_full": "USK-Coffee",
    "usk_10pct": "USK-Coffee 10%",
    "beans": "Beans",
}
ARCH_LABELS = {
    "resnet18": "ResNet-18",
    "convnext_tiny": "ConvNeXt-T",
    "swin_t": "Swin-T",
}
ABLATION_LABELS = {"no_aug": "no aug.", "res160": "160 px"}
CNN = ("resnet18", "convnext_tiny")
REVERSAL_THRESHOLD = 0.10


def headline(cells: list[dict[str, Any]]) -> dict[str, Any]:
    """The counts the text quotes, computed once from the per-cell rows."""
    k1 = [c["reversal"]["1"] for c in cells]
    k5 = [c["reversal"]["5"] for c in cells]
    stable = [c for c in cells if c["smallest_stable_k"] <= 5]
    return {
        "cells": len(cells),
        "noise_ge_half": sum(c["noise_to_effect"] >= 0.5 for c in cells),
        "noise_gt_one": sum(c["noise_to_effect"] > 1 for c in cells),
        "k1_min": min(k1),
        "k1_max": max(k1),
        "k1_median": statistics.median(k1),
        "k5_above": sum(r > REVERSAL_THRESHOLD for r in k5),
        "holm_significant": sum(bool(c["significant_holm"]) for c in cells),
        "ci_excludes_zero": sum(
            c["delta_ci95"][0] > 0 or c["delta_ci95"][1] < 0 for c in cells
        ),
        "power_median": statistics.median(c["seeds_for_power"] for c in cells),
        "power_le_ten": sum(c["seeds_for_power"] <= 10 for c in cells),
        "stable_cnn": sum(c["architecture"] in CNN for c in stable),
        "cells_cnn": sum(c["architecture"] in CNN for c in cells),
        "stable_transformer": sum(c["architecture"] not in CNN for c in stable),
        "cells_transformer": sum(c["architecture"] not in CNN for c in cells),
        # Evaluation noise belongs to the baseline, so it repeats across a pair's
        # two ablation cells; count each (dataset, architecture) once.
        "eval_below_sd": len(
            {
                (c["dataset"], c["architecture"])
                for c in cells
                if c["evaluation_half_width"] < c["baseline_sd"]
            }
        ),
        "pairs": len({(c["dataset"], c["architecture"]) for c in cells}),
        "power_min": min(c["seeds_for_power"] for c in cells),
    }


def _pct(x: float) -> str:
    return f"{100 * x:.0f}\\%"


def macros(h: dict[str, Any], hypotheses: dict[str, Any], wall_hours: float) -> str:
    """``\\newcommand`` lines for every number the text uses."""
    sd = hypotheses["H3"]["per_architecture"]
    values = {
        "NCells": h["cells"],
        "NNoiseHalf": h["noise_ge_half"],
        "NNoiseOne": h["noise_gt_one"],
        "KOneMin": _pct(h["k1_min"]),
        "KOneMax": _pct(h["k1_max"]),
        "KOneMedian": _pct(h["k1_median"]),
        "NKFiveAbove": h["k5_above"],
        "NHolm": h["holm_significant"],
        "NCIExcludes": h["ci_excludes_zero"],
        "PowerMedian": f"{h['power_median']:.0f}",
        "NPowerTen": h["power_le_ten"],
        "NStableCNN": h["stable_cnn"],
        "NCellsCNN": h["cells_cnn"],
        "NStableTr": h["stable_transformer"],
        "NCellsTr": h["cells_transformer"],
        "NEvalBelow": h["eval_below_sd"],
        "NPairs": h["pairs"],
        "PowerMin": h["power_min"],
        "WallHours": f"{wall_hours:.1f}",
        "HOne": hypotheses["H1"]["verdict"],
        "HTwo": hypotheses["H2"]["verdict"],
        "HThree": hypotheses["H3"]["verdict"],
    }
    for arch, name in (
        ("resnet18", "Res"),
        ("convnext_tiny", "Conv"),
        ("swin_t", "Swin"),
    ):
        values[f"SDFull{name}"] = f"{sd[arch]['sd_full']:.3f}"
        values[f"SDTen{name}"] = f"{sd[arch]['sd_10pct']:.3f}"
    lines = [
        "% Generated by make_paper_assets.py from results/summary.json. Do not edit."
    ]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in values.items()]
    return "\n".join(lines) + "\n"


def table_rows(cells: list[dict[str, Any]]) -> str:
    """One LaTeX row per cell, grouped by dataset with a rule between groups."""
    out = [
        "% Generated by make_paper_assets.py from results/summary.json. Do not edit."
    ]
    previous = None
    for c in cells:
        if previous is not None and c["dataset"] != previous:
            out.append("\\midrule")
        previous = c["dataset"]
        lo, hi = c["delta_ci95"]
        rev = c["reversal"]
        out.append(
            " & ".join(
                [
                    DATASET_LABELS[c["dataset"]],
                    ARCH_LABELS[c["architecture"]],
                    ABLATION_LABELS[c["ablation"]],
                    f"{c['baseline_mean']:.3f} $\\pm$ {c['baseline_sd']:.3f}",
                    f"{c['delta']:+.3f} [{lo:+.3f}, {hi:+.3f}]",
                    f"{c['noise_to_effect']:.2f}",
                    f"{rev['1']:.2f} / {rev['3']:.2f} / {rev['5']:.2f}",
                    str(c["seeds_for_power"]),
                ]
            )
            + " \\\\"
        )
    return "\n".join(out) + "\n"


def _figures(cells: list[dict[str, Any]]) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({"font.size": 8, "font.family": "serif", "pdf.fonttype": 42})
    colors = {"usk_full": "#1b6ca8", "usk_10pct": "#e0803a", "beans": "#3a9e5f"}
    markers = {"no_aug": "o", "res160": "s"}

    fig, ax = plt.subplots(figsize=(3.4, 2.9))
    for c in cells:
        ax.scatter(
            abs(c["delta"]),
            c["baseline_sd"],
            color=colors[c["dataset"]],
            marker=markers[c["ablation"]],
            s=22,
            edgecolors="black",
            linewidths=0.4,
            zorder=3,
        )
    xs = [1e-4, 1e-1]
    ax.plot(xs, xs, color="black", linewidth=0.8, label="SD = |Δ|")
    ax.plot(
        xs,
        [0.5 * x for x in xs],
        color="black",
        linewidth=0.8,
        linestyle="--",
        label="SD = 0.5|Δ| (H1)",
    )
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlim(5e-5, 0.1)
    ax.set_ylim(4e-3, 0.08)
    ax.set_xlabel("|ablation effect Δ| (test accuracy)")
    ax.set_ylabel("baseline SD across seeds")
    handles: list[Any] = [
        plt.Line2D(
            [], [], color=col, marker="o", linestyle="", label=PLOT_DATASET_LABELS[d]
        )
        for d, col in colors.items()
    ]
    handles += [
        plt.Line2D(
            [], [], color="grey", marker=m, linestyle="", label=ABLATION_LABELS[a]
        )
        for a, m in markers.items()
    ]
    handles += ax.get_legend_handles_labels()[0]
    ax.legend(handles=handles, fontsize=6, loc="lower left", frameon=False)
    fig.tight_layout()
    fig.savefig(PAPER / "fig_noise_effect.pdf")
    fig.savefig(PAPER / "fig_noise_effect.png", dpi=150)
    plt.close(fig)

    ks = [1, 3, 5]
    fig, axes = plt.subplots(1, 3, figsize=(7.0, 2.6), sharey=True)
    styles = {"resnet18": "-", "convnext_tiny": "--", "swin_t": ":"}
    for ax, dataset in zip(axes, colors, strict=True):
        for c in (c for c in cells if c["dataset"] == dataset):
            ax.plot(
                ks,
                [c["reversal"][str(k)] for k in ks],
                color=colors[dataset],
                linestyle=styles[c["architecture"]],
                marker=markers[c["ablation"]],
                markersize=3.5,
                linewidth=1,
            )
        ax.axhline(REVERSAL_THRESHOLD, color="black", linewidth=0.7, linestyle="-.")
        ax.set_title(PLOT_DATASET_LABELS[dataset])
        ax.set_xticks(ks)
        ax.set_xlabel("seeds per variant (k)")
        ax.set_ylim(0, 0.65)
    axes[0].set_ylabel("reversal rate")
    handles = [
        plt.Line2D([], [], color="grey", linestyle=s, label=ARCH_LABELS[a])
        for a, s in styles.items()
    ]
    handles += [
        plt.Line2D(
            [], [], color="grey", marker=m, linestyle="", label=ABLATION_LABELS[a]
        )
        for a, m in markers.items()
    ]
    fig.legend(handles=handles, fontsize=7, frameon=False, loc="lower center", ncol=5)
    fig.tight_layout(rect=(0, 0.08, 1, 1))
    fig.savefig(PAPER / "fig_reversal.pdf")
    fig.savefig(PAPER / "fig_reversal.png", dpi=150)
    plt.close(fig)


def study_wall_hours() -> float:
    """The grid's total training wall time, in hours, from the per-cell reports."""
    seconds = sum(
        json.loads(p.read_text(encoding="utf-8"))["study"]["wall_time_s"]
        for p in RESULTS.glob("*__*.json")
    )
    return float(seconds) / 3600


def main() -> None:
    summary = json.loads(SUMMARY.read_text(encoding="utf-8"))
    cells = summary["cells"]
    PAPER.mkdir(exist_ok=True)
    h = headline(cells)
    (PAPER / "numbers.tex").write_text(
        macros(h, summary["hypotheses"], study_wall_hours()),
        encoding="utf-8",
        newline="\n",
    )
    (PAPER / "table_cells.tex").write_text(
        table_rows(cells), encoding="utf-8", newline="\n"
    )
    _figures(cells)
    print(json.dumps(h, indent=2))


if __name__ == "__main__":
    main()
